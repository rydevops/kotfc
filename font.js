/* =========================================================================
   font.js — a tiny 3x5 bitmap font drawn directly on the game canvas.
   Used for damage numbers, emotes and in-world labels.
   ========================================================================= */
(function () {
  'use strict';
  const GLYPHS = {
    A: '010101111101101', B: '110101110101110', C: '011100100100011', D: '110101101101110',
    E: '111100110100111', F: '111100110100100', G: '011100101101011', H: '101101111101101',
    I: '111010010010111', J: '001001001101010', K: '101101110101101', L: '100100100100111',
    M: '101111111101101', N: '110101101101101', O: '010101101101010', P: '110101110100100',
    Q: '010101101110011', R: '110101110101101', S: '011100010001110', T: '111010010010010',
    U: '101101101101111', V: '101101101101010', W: '101101111111101', X: '101101010101101',
    Y: '101101010010010', Z: '111001010100111',
    0: '111101101101111', 1: '010110010010111', 2: '110001010100111', 3: '110001010001110',
    4: '101101111001001', 5: '111100110001110', 6: '011100111101111', 7: '111001010010010',
    8: '111101111101111', 9: '111101111001110',
    '+': '000010111010000', '-': '000000111000000', '!': '010010010000010', '.': '000000000000010',
    '?': '110001010000010', ':': '000010000010000', ' ': '000000000000000', '%': '101001010100101',
    '/': '001001010100100', '♪': '011010010110110', "'": '010010000000000',
  };

  G.font = {
    // width of a string in game pixels at scale s
    measure(str, s = 1) { return str.length * 4 * s - s; },
    draw(ctx, str, x, y, color = '#fff', s = 1, shadow = '#0b0712') {
      str = String(str).toUpperCase();
      const passes = shadow ? [[shadow, 1, 0], [shadow, -1, 0], [shadow, 0, 1], [shadow, 0, -1], [shadow, 1, 1], [color, 0, 0]] : [[color, 0, 0]];
      for (const [col, ox, oy] of passes) {
        ctx.fillStyle = col;
        let cx = x;
        for (const ch of str) {
          const g = GLYPHS[ch] || GLYPHS['?'];
          for (let i = 0; i < 15; i++) {
            if (g[i] === '1') ctx.fillRect(cx + (i % 3) * s + ox, y + Math.floor(i / 3) * s + oy, s, s);
          }
          cx += 4 * s;
        }
      }
    },
    drawCentered(ctx, str, cx, y, color, s = 1, shadow) {
      this.draw(ctx, str, Math.round(cx - this.measure(String(str), s) / 2), y, color, s, shadow);
    },
  };
})();
